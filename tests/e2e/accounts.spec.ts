import { test, expect } from "@playwright/test";
import { readFileSync, mkdirSync } from "node:fs";
import { randomUUID, createHmac } from "node:crypto";
import nextEnv from "@next/env";
import postgres from "postgres";
import { testReaders, loginReader } from "./account-fixtures";
import type { ReaderState } from "../../src/lib/reader-account/types";

nextEnv.loadEnvConfig(process.cwd());
const origin = "http://localhost:3100";
test("reader accounts isolate progress, enforce one resumable mark and notify first publication", async ({ page, browser, request }) => {
  if (process.env.DATABASE_SCHEMA !== "novel_preview") throw new Error("Preview only");
  const [a, b] = testReaders();
  const sql = postgres(process.env.DATABASE_URL!, { ssl: { ca: JSON.parse(readFileSync("src/lib/db/supabase-ca.json", "utf8")), rejectUnauthorized: true }, prepare: false, max: 1, onnotice: () => {} });
  const second = await browser.newContext({ baseURL: origin }); const admin = await browser.newContext({ baseURL: origin });
  const ids: string[] = []; const prefix = `E2E-account-${randomUUID()}`;
  const keys = ["reader-auth", "admin-login"].map(scope => createHmac("sha256", process.env.RATE_LIMIT_SECRET!).update(`${scope}:local-or-unknown`).digest("hex"));
  const prior = await sql`select * from novel_preview.rate_limits where key in ${sql(keys)}`;
  const state = async (): Promise<ReaderState> => (await page.context().request.get("/api/reader")).json();
  const post = (data: unknown) => page.context().request.post("/api/reader", { headers: { origin }, data });
  try {
    await sql`delete from novel_preview.rate_limits where key in ${sql(keys)}`;
    expect((await request.get("/api/reader")).headers()["cache-control"]).toContain("no-store");
    expect((await request.post("/api/reader", { headers: { origin }, data: { action: "progress", chapterId: randomUUID(), progress: 1 } })).status()).toBe(401);
    await page.goto("/dang-nhap");
    await expect(page.getByRole("tab", { name: "Đăng nhập", exact: true })).toHaveAttribute("aria-selected", "true");
    await page.getByLabel("Email", { exact: true }).fill(a.email); await page.getByLabel("Mật khẩu", { exact: true }).fill(a.password);
    await page.getByRole("button", { name: "Đăng nhập", exact: true }).click();
    await expect(page).toHaveURL(`${origin}/tai-khoan`);
    await expect(page.getByRole("heading", { name: `Xin chào, ${a.displayName}` })).toBeVisible();
    const cookies = await page.context().cookies();
    expect(cookies.filter(c => c.name.startsWith("novel_reader_")).every(c => c.httpOnly && c.sameSite === "Lax")).toBe(true);
    expect(cookies.some(c => c.name === "novel_admin")).toBe(false);
    expect((await page.context().request.get("/api/admin/overview")).status()).toBe(401);
    await loginReader(second, b); await second.request.get("/api/reader");
    const password = /^preview admin password: (.+)$/m.exec(readFileSync(".local/admin-access.txt", "utf8"))![1];
    if ((await admin.request.post("/api/admin/session", { headers: { origin }, data: { password } })).status() !== 200) throw new Error("Admin test login failed; credentials hidden");
    async function publish(position: number, intent = "publish") {
      const response = await admin.request.post("/api/admin/chapters", { headers: { origin }, data: { position, title: `${prefix} ${position}`, content: Array.from({ length: 100 }, (_, i) => `Đoạn ${i}: Một đoạn văn dài để kiểm tra vị trí đọc theo màn hình, giữ thụt đầu dòng và giãn đoạn. Câu chuyện tiếp tục qua từng dòng chữ.`).join("\n"), intent } });
      expect(response.status()).toBe(200); const chapter = (await response.json()).chapter; ids.push(chapter.id); return chapter;
    }
    const c1 = await publish(2000000901); const c2 = await publish(2000000902); const draft = await publish(2000000903, "draft");
    expect((await state()).notifications.some(n => n.chapter_id === c1.id && n.unread)).toBe(true);
    expect((await state()).notifications.some(n => n.chapter_id === draft.id)).toBe(false);
    expect((await request.get(`/chuong/${draft.id}`)).status()).toBe(404);
    await page.goto(`/chuong/${c1.id}`);
    await expect.poll(async () => (await state()).progress.find(p => p.chapter_id === c1.id)?.progress).toBe(0);
    await page.getByRole("button", { name: "Mục lục", exact: false }).first().click();
    await expect(page.locator("#reader-toc").getByRole("link").filter({ hasText: c1.title })).toContainText("Đang đọc");
    await expect(page.locator("#reader-toc").getByRole("link").filter({ hasText: c2.title })).toContainText("Chưa đọc");
    await page.keyboard.press("Escape");
    await page.getByRole("button", { name: "Xuống cuối chương", exact: true }).click();
    await expect.poll(async () => (await state()).progress.find(p => p.chapter_id === c1.id)?.progress ?? 0).toBeGreaterThanOrEqual(.9);
    await page.evaluate(() => document.querySelectorAll(".chapter-content p")[40].scrollIntoView());
    await page.getByRole("button", { name: "Đặt dấu ở vị trí hiện tại", exact: true }).click();
    await expect(page.getByRole("status")).toContainText("Đã đặt dấu");
    const mark = (await state()).bookmark!; expect(mark.chapter_id).toBe(c1.id); expect(mark.paragraph).toBeGreaterThan(20);
    const other: ReaderState = await (await second.request.get("/api/reader")).json();
    expect(other.bookmark).toBeNull(); expect(other.progress.some(p => p.chapter_id === c1.id)).toBe(false);
    expect((await second.request.post("/api/reader", { headers: { origin }, data: { action: "remove-bookmark", id: mark.id, user_id: a.id } })).status()).toBe(409);
    expect((await post({ action: "bookmark", chapterId: c2.id, paragraph: 0, offset: 0 })).status()).toBe(409);
    expect((await post({ action: "progress", chapterId: c1.id, progress: .1 })).status()).toBe(409);
    await page.reload();
    const dialog = page.getByRole("dialog", { name: "Vị trí đọc đã đánh dấu" }); await expect(dialog).toBeVisible();
    await page.keyboard.press("Escape"); await expect(dialog).toBeVisible();
    await page.route("**/api/reader", route => route.request().method() === "POST" ? route.abort() : route.continue());
    await dialog.getByRole("button", { name: "Bỏ dấu và đọc tiếp", exact: true }).click(); await expect(dialog.getByRole("alert")).toBeVisible(); await expect(dialog).toBeVisible();
    await page.unroute("**/api/reader");
    await dialog.getByRole("button", { name: "Bỏ dấu và đọc tiếp", exact: true }).click(); await expect(dialog).not.toBeVisible();
    expect((await state()).bookmark).toBeNull();
    const race = await Promise.all([post({ action: "bookmark", chapterId: c1.id, paragraph: 1, offset: .2 }), post({ action: "bookmark", chapterId: c2.id, paragraph: 2, offset: .4 })]);
    expect(race.map(r => r.status()).sort()).toEqual([200, 409]);
    expect((await post({ action: "remove-bookmark", id: mark.id })).status()).toBe(409);
    const nextMark = (await state()).bookmark!;
    expect((await post({ action: "remove-bookmark", id: nextMark.id })).status()).toBe(200);
    expect((await post({ action: "progress", chapterId: c1.id, progress: .1 })).status()).toBe(200);
    expect((await state()).progress.find(p => p.chapter_id === c1.id)!.progress).toBeGreaterThanOrEqual(.9);
    expect((await post({ action: "progress", chapterId: draft.id, progress: 1 })).status()).toBe(409);
    expect((await post({ action: "bookmark", chapterId: c1.id, paragraph: 9999, offset: 0 })).status()).toBe(400);
    expect((await page.context().request.post("/api/reader", { headers: { origin: "https://evil.example" }, data: { action: "profile", displayName: "X" } })).status()).toBe(403);
    const firstDate = (await state()).notifications.find(n => n.chapter_id === c1.id)!.created_at;
    const base = { id: c1.id, position: c1.position, title: c1.title, content: c1.content };
    expect((await admin.request.post("/api/admin/chapters", { headers: { origin }, data: { ...base, intent: "unpublish" } })).status()).toBe(200);
    expect((await state()).notifications.some(n => n.chapter_id === c1.id)).toBe(false);
    expect((await admin.request.post("/api/admin/chapters", { headers: { origin }, data: { ...base, intent: "publish" } })).status()).toBe(200);
    expect((await state()).notifications.find(n => n.chapter_id === c1.id)!.created_at).toBe(firstDate);
    const snapshot = await state();
    expect((await post({ action: "read-notifications", before: snapshot.notifications[0].created_at })).status()).toBe(200);
    expect((await state()).unread).toBe(0);
    await page.setViewportSize({ width: 390, height: 844 }); await page.goto("/tai-khoan");
    await expect(page.getByRole("heading", { name: "Tiến độ đọc", exact: true })).toBeVisible();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
    mkdirSync(".local", { recursive: true }); await page.screenshot({ path: ".local/account-mobile.png", fullPage: true });
    expect((await page.context().request.post("/api/reader/auth", { headers: { origin }, data: { action: "logout" } })).status()).toBe(200);
    expect((await state()).profile).toBeNull();
  } finally {
    if (ids.length) await sql`delete from novel_preview.chapters where id in ${sql(ids)}`;
    await sql`delete from novel_preview.rate_limits where key in ${sql(keys)}`;
    for (const row of prior) await sql`insert into novel_preview.rate_limits(key,attempts,reset_at) values(${row.key},${row.attempts},${row.reset_at})`;
    await second.close(); await admin.close(); await sql.end();
  }
});
