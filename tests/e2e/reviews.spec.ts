import { test, expect } from "@playwright/test";
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { createHmac, randomUUID } from "node:crypto";
import nextEnv from "@next/env";
import postgres from "postgres";
import { loginReader, testReaders } from "./account-fixtures";
import type { ReviewPage } from "../../src/lib/reviews/types";

nextEnv.loadEnvConfig(process.cwd());
const origin = "http://localhost:3100";
test("signed-in reviews persist ownership, validate, limit, moderate and retain legacy pagination", async ({ page, browser, request }) => {
  if (process.env.DATABASE_SCHEMA !== "novel_preview") throw new Error("Preview only");
  const [reader] = testReaders();
  const sql = postgres(process.env.DATABASE_URL!, { ssl: { ca: JSON.parse(readFileSync("src/lib/db/supabase-ca.json", "utf8")), rejectUnauthorized: true }, prepare: false, max: 1, onnotice: () => {} });
  const id = randomUUID(); const prefix = `E2E-review-${randomUUID()}`;
  const keys = ["review:local-or-unknown", `review:${reader.id}`, "reader-auth:local-or-unknown", "admin-login:local-or-unknown"].map(value => createHmac("sha256", process.env.RATE_LIMIT_SECRET!).update(value).digest("hex"));
  const prior = await sql`select * from novel_preview.rate_limits where key in ${sql(keys)}`;
  const admin = await browser.newContext({ baseURL: origin });
  try {
    await sql`delete from novel_preview.rate_limits where key in ${sql(keys)}`;
    await sql`insert into novel_preview.chapters(id,position,title,content,status,published_at) values(${id},2000000801,${prefix},'Một chương kiểm thử.','published',now())`;
    expect((await request.post("/api/reviews", { headers: { origin }, data: { rating: 5 } })).status()).toBe(401);
    expect((await request.post("/api/reviews", { headers: { origin: "https://evil.example" }, data: {} })).status()).toBe(403);
    await page.goto(`/chuong/${id}`);
    await expect(page.getByRole("link", { name: "Đăng nhập để đánh giá" })).toBeVisible();
    await loginReader(page.context(), reader);
    await page.reload();
    const section = page.locator("#danh-gia");
    await expect(section.getByText(reader.displayName, { exact: true })).toBeVisible();
    const post = (data: unknown) => page.context().request.post("/api/reviews", { headers: { origin }, data });
    for (const data of [{ rating: "5" }, { rating: 0 }, { rating: 6 }, { rating: 2.5 }, { rating: 5, comment: "x".repeat(1001) }, { rating: 5, website: "spam" }]) expect((await post(data)).status()).toBe(400);
    expect((await post({ rating: 5, comment: "x".repeat(17000) })).status()).toBe(413);
    const comment = `${prefix}\n<script>window.__reviewXss=1</script>`;
    const input = section.getByLabel("Nhận xét", { exact: false });
    await input.fill(comment);
    for (const type of ["copy", "cut", "contextmenu"]) expect(await input.evaluate((element, t) => element.dispatchEvent(new Event(t, { bubbles: true, cancelable: true })), type)).toBe(true);
    await section.getByRole("radio", { name: "5 sao", exact: true }).check();
    await page.route("**/api/reviews", route => route.request().method() === "POST" ? route.abort() : route.continue());
    await section.getByRole("button", { name: "Gửi đánh giá", exact: true }).click();
    await expect(section.getByRole("alert")).toContainText("Nội dung vẫn được giữ");
    await expect(input).toHaveValue(comment); await page.unroute("**/api/reviews");
    await section.getByRole("button", { name: "Gửi đánh giá", exact: true }).click();
    await expect(section.getByRole("status")).toContainText("Đã gửi đánh giá");
    const [saved] = await sql`select id,user_id,created_at,display_name from novel_preview.reviews where comment=${comment}`;
    expect(saved.user_id).toBe(reader.id); expect(saved.display_name).toBe(reader.displayName); expect(saved.created_at).toBeTruthy();
    expect((await post({ displayName: "mạo danh", rating: 1 })).status()).toBe(429);
    const account = await (await page.context().request.get("/api/reader")).json();
    expect(account.reviews.some((r: { id: string }) => r.id === saved.id)).toBe(true);
    await page.reload(); await expect(section.locator(".review-list")).toContainText(comment);
    expect(await page.evaluate(() => "__reviewXss" in window)).toBe(false);
    const password = /^preview admin password: (.+)$/m.exec(readFileSync(".local/admin-access.txt", "utf8"))![1];
    const login = await admin.request.post("/api/admin/session", { headers: { origin }, data: { password } });
    if (login.status() !== 200) throw new Error("Admin login failed; credentials hidden");
    expect((await admin.request.post("/api/admin/reviews", { headers: { origin }, data: { id: saved.id } })).status()).toBe(200);
    const visible: ReviewPage = await (await request.get("/api/reviews")).json();
    expect(visible.reviews.some(r => r.id === saved.id)).toBe(false);
    const own = await (await page.context().request.get("/api/reader")).json();
    expect(own.reviews.find((r: { id: string }) => r.id === saved.id).is_hidden).toBe(true);
    await sql`insert into novel_preview.reviews(display_name,rating,comment) select ${prefix}||n,4,'Legacy pagination fixture' from generate_series(1,12)n`;
    const first: ReviewPage = await (await request.get("/api/reviews")).json();
    const last = first.reviews.at(-1)!;
    const second: ReviewPage = await (await request.get(`/api/reviews?before=${encodeURIComponent(`${last.created_at}|${last.id}`)}`)).json();
    expect(first.reviews).toHaveLength(10); expect(second.reviews.length).toBeGreaterThan(0);
    expect(new Set([...first.reviews, ...second.reviews].map(r => r.id)).size).toBe(first.reviews.length + second.reviews.length);
  } finally {
    const rows = await sql`select id from novel_preview.reviews where comment like ${`${prefix}%`} or display_name like ${`${prefix}%`}`;
    mkdirSync(".local", { recursive: true }); const path = ".local/reader-review-fixtures.json";
    const previous = existsSync(path) ? JSON.parse(readFileSync(path, "utf8")) : [];
    writeFileSync(path, JSON.stringify([...new Set([...previous, ...rows.map(row => row.id)])]));
    if (rows.length) await sql`update novel_preview.reviews set is_hidden=true where id in ${sql(rows.map(row => row.id))}`;
    await sql`delete from novel_preview.chapters where id=${id}`;
    await sql`delete from novel_preview.rate_limits where key in ${sql(keys)}`;
    for (const row of prior) await sql`insert into novel_preview.rate_limits(key,attempts,reset_at) values(${row.key},${row.attempts},${row.reset_at})`;
    await admin.close(); await sql.end();
  }
});
