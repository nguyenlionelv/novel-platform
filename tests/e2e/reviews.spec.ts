import { test, expect } from "@playwright/test";
import { readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { randomUUID, createHmac } from "node:crypto";
import nextEnv from "@next/env";
import postgres from "postgres";
import type { ReviewPage } from "../../src/lib/reviews/types";

nextEnv.loadEnvConfig(process.cwd());
const origin = "http://localhost:3100";

test("anonymous reviews validate, rate limit, paginate and disappear from totals when hidden", async ({ page, browser, request }) => {
  if (process.env.DATABASE_SCHEMA !== "novel_preview") throw new Error("Review E2E is restricted to preview");
  const password = /^preview admin password: (.+)$/m.exec(readFileSync(".local/admin-access.txt", "utf8"))?.[1];
  if (!password) throw new Error("Preview admin password missing; value hidden");
  const sql = postgres(process.env.DATABASE_URL!, { ssl: { ca: JSON.parse(readFileSync("src/lib/db/supabase-ca.json", "utf8")), rejectUnauthorized: true }, prepare: false, max: 1, onnotice: () => {} });
  const prefix = `E2E-review-${randomUUID().slice(0, 8)}`;
  const admin = await browser.newContext({ baseURL: origin });
  const scopes = ["admin-login", "review"];
  const keys = scopes.map(scope => createHmac("sha256", process.env.RATE_LIMIT_SECRET!).update(`${scope}:local-or-unknown`).digest("hex"));
  const originalLimits = await sql`select * from novel_preview.rate_limits where key in ${sql(keys)}`;
  const [original] = await sql`select count(*)::int as count, coalesce(sum(rating),0)::int as sum from novel_preview.reviews where is_hidden=false`;
  const post = (data: unknown, headers: Record<string, string> = { origin }) => request.post("/api/reviews", { headers, data });
  try {
    await sql`delete from novel_preview.rate_limits where key in ${sql(keys)}`;
    expect((await request.post("/api/reviews", { data: {} })).status()).toBe(403);
    expect((await post({}, { origin: "https://attacker.example" })).status()).toBe(403);
    expect((await post({ displayName: "x".repeat(17000), rating: 5 })).status()).toBe(413);
    for (const data of [{ displayName: " ", rating: 5 }, { displayName: "x".repeat(51), rating: 5 }, { displayName: "A", rating: "5" }, { displayName: "A", rating: 2.5 }, { displayName: "A", rating: 0 }, { displayName: "A", rating: 6 }, { displayName: "A", rating: 5, comment: "x".repeat(1001) }, { displayName: "A", rating: 5, website: "spam" }]) expect((await post(data)).status()).toBe(400);
    expect((await sql`select count(*)::int as count from novel_preview.rate_limits where key=${keys[1]}`)[0].count).toBe(0);
    expect((await request.get("/api/reviews?before=bad-cursor")).status()).toBe(400);
    expect((await request.get("/api/reviews")).headers()["cache-control"]).toContain("no-store");
    await page.goto("/");
    const section = page.locator("section#danh-gia");
    if (!original.count) {
      await expect(section.getByText("Chưa có đánh giá.", { exact: true })).toBeVisible();
      await expect(section.locator("#review-summary")).not.toContainText("0,0");
    }
    await expect(section.getByRole("radio", { checked: true })).toHaveCount(0);
    await section.getByLabel("Tên của bạn", { exact: true }).fill(`${prefix} độc giả`);
    await section.getByRole("radio", { name: "5 sao", exact: true }).check();
    const comment = "Một câu chuyện rất đẹp.\n<script>window.__reviewXss = 1</script>";
    const commentBox = section.getByLabel("Nhận xét", { exact: false });
    await commentBox.fill(comment);
    expect(await commentBox.evaluate((element: HTMLTextAreaElement) => { element.select(); return element.selectionEnd - element.selectionStart; })).toBe(comment.length);
    for (const type of ["copy", "cut", "contextmenu"]) expect(await commentBox.evaluate((element, eventType) => element.dispatchEvent(new Event(eventType, { bubbles: true, cancelable: true })), type)).toBe(true);
    await page.route("**/api/reviews", route => route.request().method() === "POST" ? route.abort() : route.continue());
    await section.getByRole("button", { name: "Gửi đánh giá", exact: true }).click();
    await expect(section.getByRole("alert")).toContainText("Nội dung vẫn được giữ");
    await expect(commentBox).toHaveValue(comment);
    await page.unroute("**/api/reviews");
    await section.getByRole("button", { name: "Gửi đánh giá", exact: true }).click();
    await expect(section.getByRole("status")).toHaveText("Đã gửi đánh giá.");
    await expect(section.getByText(`${prefix} độc giả`, { exact: true })).toBeVisible();
    await expect(section.locator("#review-summary")).toContainText(`${original.count + 1} đánh giá`);
    const expectedAverage = ((original.sum + 5) / (original.count + 1)).toFixed(1).replace(".", ",");
    await expect(section.locator("#review-summary")).toContainText(expectedAverage);
    expect(await page.evaluate(() => "__reviewXss" in window)).toBe(false);
    const [created] = await sql`select id, display_name, rating, comment from novel_preview.reviews where display_name=${`${prefix} độc giả`}`;
    expect(created.rating).toBe(5); expect(created.comment).toBe(comment);
    await page.reload();
    await expect(section.getByText(`${prefix} độc giả`, { exact: true })).toBeVisible();
    expect((await page.context().cookies()).some(cookie => cookie.name === "novel_admin")).toBe(false);
    expect((await post({ displayName: `${prefix} rate blocked`, rating: 1 })).status()).toBe(429);
    await section.getByLabel("Tên của bạn", { exact: true }).fill(`${prefix} bị giới hạn`);
    await section.getByRole("radio", { name: "1 sao", exact: true }).check();
    await commentBox.fill("Nội dung được giữ sau lỗi 429.");
    await section.getByRole("button", { name: "Gửi đánh giá", exact: true }).click();
    await expect(section.getByRole("alert")).toContainText("đợi một phút");
    await expect(commentBox).toHaveValue("Nội dung được giữ sau lỗi 429.");
    expect((await post({ displayName: `${prefix} cannot spoof IP`, rating: 1 }, { origin, "x-forwarded-for": "203.0.113.101" })).status()).toBe(429);
    await sql`delete from novel_preview.rate_limits where key=${keys[1]}`;
    const concurrent = await Promise.all([post({ displayName: `${prefix} concurrent`, rating: 3 }), post({ displayName: `${prefix} concurrent`, rating: 3 })]);
    expect(concurrent.map(response => response.status()).sort()).toEqual([201, 429]);

    expect((await admin.request.post("/api/admin/session", { headers: { origin }, data: { password } }).catch(() => { throw new Error("Admin login failed; value hidden"); })).status()).toBe(200);
    const adminPage = await admin.newPage();
    await adminPage.goto("/admin");
    const adminRow = adminPage.locator("#danh-gia li").filter({ hasText: `${prefix} độc giả` });
    await adminRow.getByRole("button", { name: "Ẩn đánh giá", exact: true }).click();
    await expect(adminRow.getByRole("button", { name: "Đã ẩn", exact: true })).toBeDisabled();
    expect((await sql`select is_hidden from novel_preview.reviews where id=${created.id}`)[0].is_hidden).toBe(true);
    const afterHide: ReviewPage = await (await request.get("/api/reviews")).json();
    expect(afterHide.reviews.some(review => review.id === created.id)).toBe(false);
    expect(afterHide.summary.count).toBe(original.count + 1);
    expect(afterHide.summary.average).toBeCloseTo((original.sum + 3) / (original.count + 1));
    const html = await (await request.get("/")).text();
    expect(html.includes(`${prefix} độc giả`)).toBe(false);
    expect(html.includes("__reviewXss")).toBe(false);
    await sql`insert into novel_preview.reviews (display_name,rating,comment) select ${prefix} || ' pagination ' || n, 4, 'Pagination fixture' from generate_series(1,12) n`;
    await page.reload();
    const list = section.getByRole("list", { name: "Đánh giá của độc giả" });
    await expect(list.locator("li")).toHaveCount(10);
    await page.setViewportSize({ width: 390, height: 844 });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
    mkdirSync(".local", { recursive: true });
    await section.screenshot({ path: ".local/stage5-reviews-mobile.png" });
    await section.getByRole("button", { name: "Xem thêm đánh giá" }).click();
    await expect(list.locator("li")).toHaveCount(Math.min(original.count + 13,20));
    const all: ReviewPage = await (await request.get("/api/reviews")).json();
    const last = all.reviews.at(-1)!;
    const more: ReviewPage = await (await request.get(`/api/reviews?before=${encodeURIComponent(`${last.created_at}|${last.id}`)}`)).json();
    expect(new Set([...all.reviews, ...more.reviews].map(review => review.id)).size).toBe(all.reviews.length + more.reviews.length);
  } finally {
    mkdirSync(".local", { recursive: true });
    const fixturePath = ".local/stage5-review-fixtures.json";
    const prior: string[] = existsSync(fixturePath) ? JSON.parse(readFileSync(fixturePath,"utf8")) : [];
    const rows = await sql`select id from novel_preview.reviews where display_name like ${`${prefix}%`}`;
    writeFileSync(fixturePath, JSON.stringify([...new Set([...prior,...rows.map(row=>row.id)])]));
    if (rows.length) await sql`update novel_preview.reviews set is_hidden=true where id in ${sql(rows.map(row=>row.id))}`;
    await sql`delete from novel_preview.rate_limits where key in ${sql(keys)}`;
    for (const row of originalLimits) await sql`insert into novel_preview.rate_limits (key,attempts,reset_at) values (${row.key},${row.attempts},${row.reset_at})`;
    await admin.close(); await sql.end();
  }
});
